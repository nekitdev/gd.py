# month days: Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec
from gd.strings.constants import SPACE


MONTH_DAYS = (31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31)

SECONDS_TO_MILLISECONDS = 1000
MINUTES_TO_SECONDS = 60
HOURS_TO_MINUTES = 60
DAYS_TO_HOURS = 24
WEEKS_TO_DAYS = 7
MONTHS_TO_DAYS = sum(MONTH_DAYS) / len(MONTH_DAYS)
YEARS_TO_DAYS = 365

MILLISECOND_MILLISECONDS = 1  # obviously

SECOND_MILLISECONDS = MILLISECOND_MILLISECONDS * SECONDS_TO_MILLISECONDS
MINUTE_MILLISECONDS = SECOND_MILLISECONDS * MINUTES_TO_SECONDS
HOUR_MILLISECONDS = MINUTE_MILLISECONDS * HOURS_TO_MINUTES
DAY_MILLISECONDS = HOUR_MILLISECONDS * DAYS_TO_HOURS
WEEK_MILLISECONDS = DAY_MILLISECONDS * WEEKS_TO_DAYS
MONTH_MILLISECONDS = int(DAY_MILLISECONDS * MONTHS_TO_DAYS)
YEAR_MILLISECONDS = DAY_MILLISECONDS * YEARS_TO_DAYS

NOW = "now"

IN = "in"
AGO = "ago"

MILLISECOND = "millisecond"
SECOND = "second"
MINUTE = "minute"
HOUR = "hour"
DAY = "day"
WEEK = "week"
MONTH = "month"
YEAR = "year"

S_LITERAL = "s"

SEPARATOR = ","

SEPARATOR_SPACE = SEPARATOR + SPACE

NAME_TO_MILLISECONDS = {
    MILLISECOND: MILLISECOND_MILLISECONDS,
    SECOND: SECOND_MILLISECONDS,
    MINUTE: MINUTE_MILLISECONDS,
    HOUR: HOUR_MILLISECONDS,
    DAY: DAY_MILLISECONDS,
    WEEK: WEEK_MILLISECONDS,
    MONTH: MONTH_MILLISECONDS,
    YEAR: YEAR_MILLISECONDS,
}

MILLISECONDS_TO_NAME = {milliseconds: name for name, milliseconds in NAME_TO_MILLISECONDS.items()}
MILLISECONDS_TO_NAME_SEARCH = sorted(MILLISECONDS_TO_NAME.items(), reverse=True)
